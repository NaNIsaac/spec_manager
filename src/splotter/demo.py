"""Write a made-up SPEC file to try the commands on and to test them with. Nothing in it is measured.

The same file comes out every time. Its scans:

    1      mesh of sx and sy, with one bright spot at sx = 0.4, sy = -0.3
    2      mesh next to scan 1, overlapping it
    3, 4   ascan of sx and of sy through the bright spot
    5      mesh aborted after 100 of its 231 points
    6-8    rocking scans of th; the scan list for `splotter fwhm` names them
"""

import argparse
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np

START = datetime(2026, 1, 1, 9, 0, 0)
TIME_FORMAT = "%a %b %d %H:%M:%S %Y"
SEED = 2032
COUNT_TIME = 0.5
ENERGY_KEV = 8.0
SPOT_X, SPOT_Y = 0.4, -0.3
# (name, mnemonic, position)
MOTORS = [
    ("Delta", "del", 50.9),
    ("Theta", "th", 25.45),
    ("Chi", "chi", 90.0),
    ("Phi", "phi", 0.0),
    ("Mu", "mu", 0.0),
    ("Gamma", "gam", 0.0),
    ("Sample_X", "sx", 0.0),
    ("Sample_Y", "sy", 0.0),
]
MOTORS_PER_LINE = 4
# (scan, sigma of the rocking curve [deg], delta [deg])
ROCKING_SCANS = [(6, 0.03, 30.0), (7, 0.05, 40.0), (8, 0.07, 50.0)]


def blob(x, y, centre_x: float, centre_y: float, width: float) -> np.ndarray:
    return np.exp(-((x - centre_x) ** 2 + (y - centre_y) ** 2) / (2 * width**2))


def sample_signal(x, y) -> np.ndarray:
    """Counts above the background at a sample position: a bright spot and a weak one."""
    return 1e5 * blob(x, y, SPOT_X, SPOT_Y, 0.08) + 3e3 * blob(x, y, 1.2, 0.2, 0.15)


def counters(rng: np.random.Generator, signal: np.ndarray) -> dict[str, np.ndarray]:
    roi1 = rng.poisson(0.02 * signal)
    roi2 = rng.poisson(0.05 * signal + 5)
    roi3 = rng.poisson(0.9 * signal + 600)
    return {
        "imtot": roi1 + roi2 + roi3 + rng.poisson(600, signal.shape),
        "imroi1": roi1,
        "imroi2": roi2,
        "imroi3": roi3,
        "immax": rng.poisson(np.sqrt(signal) + 150),
    }


def header() -> list[str]:
    lines = [
        "#F demo",
        f"#E {int(START.timestamp())}",
        f"#D {START.strftime(TIME_FORMAT)}",
        "#C sixc  User = demo, generated by splotter demo, not a measurement",
        "",
    ]
    for i in range(0, len(MOTORS), MOTORS_PER_LINE):
        chunk = MOTORS[i : i + MOTORS_PER_LINE]
        lines.append(f"#O{i // MOTORS_PER_LINE} " + "  ".join(name for name, _, _ in chunk))
    for i in range(0, len(MOTORS), MOTORS_PER_LINE):
        chunk = MOTORS[i : i + MOTORS_PER_LINE]
        lines.append(f"#o{i // MOTORS_PER_LINE} " + " ".join(short for _, short, _ in chunk))
    lines.append("")
    return lines


def uxml() -> list[str]:
    return [
        '#UXML <ad_center prefix="DEMO:CAM1:">',
        '#UXML   <beam_center_x type="int">256</beam_center_x>',
        '#UXML   <beam_center_y type="int">256</beam_center_y>',
        "#UXML </ad_center>",
        '#UXML <ad_detector prefix="DEMO:CAM1:">',
        '#UXML   <description type="str">made-up detector</description>',
        '#UXML   <sample_detector_distance type="float">600</sample_detector_distance>',
        "#UXML </ad_detector>",
        '#UXML <ad_regions_of_interest prefix="DEMO:CAM1:">',
        '#UXML   <roi number="1">',
        '#UXML     <min_x type="int">250</min_x>',
        '#UXML     <size_x type="int">12</size_x>',
        "#UXML   </roi>",
        '#UXML   <roi number="2">',
        '#UXML     <min_x type="int">200</min_x>',
        '#UXML     <size_x type="int">112</size_x>',
        "#UXML   </roi>",
        "#UXML </ad_regions_of_interest>",
    ]


class Writer:
    """Collects scans, with the clock and the random numbers running from one scan to the next."""

    def __init__(self) -> None:
        self.lines = header()
        self.rng = np.random.default_rng(SEED)
        self.elapsed = 60  # seconds since the file header

    def scan(
        self,
        number: int,
        command: str,
        moved: dict[str, np.ndarray],
        signal: np.ndarray,
        *,
        positions: dict[str, float] | None = None,
        note: str | None = None,
    ) -> None:
        at = {name: value for name, _, value in MOTORS} | (positions or {})
        epoch = self.elapsed + 2 + np.arange(signal.size)
        columns = {
            **moved,
            "Epoch": epoch,
            "Seconds": np.full(signal.size, COUNT_TIME),
            **counters(self.rng, signal),
        }
        values = [str(at[name]) for name, _, _ in MOTORS]
        self.lines += [
            f"#S {number}  {command}",
            f"#D {(START + timedelta(seconds=self.elapsed)).strftime(TIME_FORMAT)}",
            f"#T {COUNT_TIME}  (Seconds)",
            "#Q 0 0 2.41728",
        ]
        for i in range(0, len(values), MOTORS_PER_LINE):
            chunk = values[i : i + MOTORS_PER_LINE]
            self.lines.append(f"#P{i // MOTORS_PER_LINE} " + " ".join(chunk))
        self.lines += [*uxml(), f"#N {len(columns)}", "#L " + "  ".join(columns)]
        for row in zip(*columns.values(), strict=True):
            self.lines.append(" ".join(f"{value:g}" for value in row))
        if note:
            self.lines.append(f"#C {note}")
        self.lines.append("")
        self.elapsed = int(epoch[-1]) + 30

    def mesh(self, number: int, sy: tuple, sx: tuple, *, points: int | None = None) -> None:
        y_axis = np.linspace(sy[0], sy[1], sy[2] + 1)
        x_axis = np.linspace(sx[0], sx[1], sx[2] + 1)
        y = np.tile(y_axis, x_axis.size)[:points]
        x = np.repeat(x_axis, y_axis.size)[:points]
        self.scan(
            number,
            f"mesh sy {sy[0]} {sy[1]} {sy[2]} sx {sx[0]} {sx[1]} {sx[2]}  {COUNT_TIME}",
            {"Sample_Y": y, "Sample_X": x},
            sample_signal(x, y),
            positions={"Sample_Y": sy[0], "Sample_X": sx[0]},
            note=f"Scan aborted after {points} points." if points else None,
        )

    def rocking(self, number: int, sigma: float, delta: float) -> None:
        theta_axis = np.linspace(delta / 2 - 0.5, delta / 2 + 0.5, 41)
        peak = 5e4 * np.exp(-((theta_axis - delta / 2) ** 2) / (2 * sigma**2))
        start, stop = theta_axis[0], theta_axis[-1]
        self.scan(
            number,
            f"ascan  th {start:g} {stop:g}  40 {COUNT_TIME}",
            {"Theta": theta_axis},
            peak,
            positions={"Delta": delta, "Theta": start},
        )


def write_demo(path: Path) -> tuple[Path, Path]:
    """Write the SPEC file and, next to it, the scan list for `splotter fwhm`; return both paths."""
    writer = Writer()
    writer.mesh(1, sy=(-1, 1, 20), sx=(-1, 1, 20))
    writer.mesh(2, sy=(-1, 1, 20), sx=(0.8, 1.8, 10))

    x = np.linspace(0.2, 0.6, 21)
    writer.scan(
        3,
        f"ascan  sx 0.2 0.6  20 {COUNT_TIME}",
        {"Sample_X": x},
        sample_signal(x, SPOT_Y),
        positions={"Sample_X": 0.2, "Sample_Y": SPOT_Y},
    )
    y = np.linspace(-0.5, -0.1, 21)
    writer.scan(
        4,
        f"ascan  sy -0.5 -0.1  20 {COUNT_TIME}",
        {"Sample_Y": y},
        sample_signal(SPOT_X, y),
        positions={"Sample_X": SPOT_X, "Sample_Y": -0.5},
    )
    writer.mesh(5, sy=(1, 2, 10), sx=(-1, 1, 20), points=100)
    for number, sigma, delta in ROCKING_SCANS:
        writer.rocking(number, sigma, delta)

    path.write_text("\n".join(writer.lines), encoding="utf-8")
    scan_list = path.with_name(f"{path.stem}_fwhm.csv")
    rows = [f"{no},0.0,{delta},{delta / 2}\n" for no, _, delta in ROCKING_SCANS]
    scan_list.write_text("".join(rows), encoding="utf-8")
    return path, scan_list


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="splotter demo",
        description="Write a made-up SPEC file to try the commands on; nothing in it is measured.",
    )
    parser.add_argument("out", type=Path, help="SPEC file to write, e.g. demo.spec")
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    scan_list = args.out.with_name(f"{args.out.stem}_fwhm.csv")
    if not args.force:
        for path in (args.out, scan_list):
            if path.exists():
                raise SystemExit(f"'{path}' exists; --force overwrites it")

    for path in write_demo(args.out):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
